import { describe, expect, it, vi } from 'vitest'
import { TileImageCache, TileImageRequest } from './tileImageCache'

describe('suggestion tile images', () => {
  it('coalesces concurrent images, reuses decoded images and keeps river modes separate', async () => {
    const render = vi.fn(async (seq: string, river: boolean) => seq + river)
    const cache = new TileImageCache(render)
    expect(cache.get('1m')).toBe(cache.get('1m'))
    await cache.get('1m')
    expect(cache.peek('1m')).toBe('1mfalse')
    await cache.get('1m', true)
    expect(render).toHaveBeenCalledTimes(2)
  })
  it('never publishes a slow old render after a newer suggestion', async () => {
    const resolves = new Map<string, (src: string) => void>()
    const cache = new TileImageCache((seq) => new Promise((resolve) => resolves.set(seq, resolve)))
    const request = new TileImageRequest(cache)
    const publish = vi.fn()
    request.update('1m', false, publish)
    await Promise.resolve()
    request.update('2m', false, publish)
    await Promise.resolve()
    expect(publish.mock.calls.at(-1)).toEqual([undefined])
    resolves.get('2m')!('new')
    await cache.get('2m')
    await Promise.resolve()
    resolves.get('1m')!('old')
    await cache.get('1m')
    await Promise.resolve()
    expect(publish.mock.calls.at(-1)).toEqual(['new'])
    expect(publish).not.toHaveBeenCalledWith('old')
  })
  it('publishes a cached image synchronously and ignores unmounted work', async () => {
    const cache = new TileImageCache(async () => 'ready')
    await cache.get('3m')
    const publish = vi.fn()
    const request = new TileImageRequest(cache)
    request.update('3m', false, publish)
    expect(publish).toHaveBeenLastCalledWith('ready')
    request.update('4m', false, publish)
    request.cancel()
    await cache.get('4m')
    expect(publish).toHaveBeenLastCalledWith(undefined)
  })
  it('retries failed renders and bounds retained images', async () => {
    const render = vi.fn().mockRejectedValueOnce(new Error('decode')).mockResolvedValue('image')
    const cache = new TileImageCache(render, 2)
    await expect(cache.get('1m')).rejects.toThrow('decode')
    await cache.get('1m')
    await cache.get('2m')
    await cache.get('3m')
    expect(cache.peek('1m')).toBeUndefined()
    expect(cache.peek('2m')).toBe('image')
  })
})
